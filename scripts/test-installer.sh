#!/usr/bin/env bash
# Exercise the real installer with a tiny offline release and isolated user dirs.
set -euo pipefail
real_bun=$(command -v bun || true)
original_path=$PATH
root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
export HOME="$tmp/home" PATH="$tmp/tools:/usr/bin:/bin"
mkdir -p "$HOME" "$tmp/tools" "$tmp/source with spaces/bin"
source_dir="$tmp/source with spaces"
printf '{"name":"solvebench","version":"0.1.0-alpha.1"}\n' > "$source_dir/package.json"
printf '# lock\n' > "$source_dir/bun.lock"
cp "$root/bin/pairs" "$source_dir/bin/pairs"
# Wrapper is supplied by the release, not generated by the installer.
[[ ! -f "$root/bin/solvebench" ]] || cp "$root/bin/solvebench" "$source_dir/bin/solvebench"
cat > "$tmp/tools/bun" <<'BUN'
#!/usr/bin/env bash
set -euo pipefail
if [[ "${1:-}" == install ]]; then
  [[ "${2:-}" == --frozen-lockfile ]]
  [[ "${FAIL_INSTALL:-0}" != 1 ]] || exit 23
  [[ "${SLOW_INSTALL:-0}" != 1 ]] || sleep 2
  exit 0
fi
for arg in "$@"; do
  if [[ "$arg" == --version ]]; then printf 'solvebench %s\n' "${SMOKE_VERSION:-0.1.0-alpha.1}"; exit; fi
done
printf '%s\n' "$PWD" "$@"
BUN
chmod +x "$tmp/tools/bun"
pass() { printf 'PASS %s\n' "$1"; }
fail() { printf 'FAIL %s\n' "$1" >&2; exit 1; }
install() { bash "$root/install.sh" --source "$source_dir" "$@" > "$tmp/log" 2>&1; }
# Local source installs must not copy developer tokens or exercise workspaces.
for private in .env .env.local solvebench.config.json pairharness.config.json; do printf 'secret\n' > "$source_dir/$private"; done
for private in .solvebench .pairharness exercises .exercism-cli .goal .scratch; do
  mkdir -p "$source_dir/$private"
  printf 'private\n' > "$source_dir/$private/keep"
done
printf 'PUBLIC_EXAMPLE=\n' > "$source_dir/.env.example"
prefix="$tmp/user prefix"
install --prefix "$prefix" || { cat "$tmp/log"; fail 'local source installation'; }
base="$prefix/share/solvebench"
[[ -L "$base/current" && -x "$prefix/bin/solvebench" ]] || fail 'installed paths'
[[ $("$prefix/bin/solvebench" --version) == 'solvebench 0.1.0-alpha.1' ]] || fail 'version smoke'
output=$(cd / && "$prefix/bin/solvebench" --sample 'argument with spaces')
[[ "$output" == *"$base/workspace"* && "$output" == *'argument with spaces'* ]] || fail 'managed workspace and args'
explicit=$(cd / && "$prefix/bin/solvebench" --repo "$tmp/explicit workspace")
[[ "$explicit" == *"$tmp/explicit workspace"* && "$explicit" != *"$base/workspace"* ]] || fail 'explicit workspace ignored'
for private in .env .env.local solvebench.config.json pairharness.config.json .solvebench .pairharness exercises .exercism-cli .goal .scratch; do
  [[ ! -e "$base/current/$private" ]] || fail "private source content copied: $private"
done
[[ -f "$base/current/.env.example" ]] || fail 'public environment example omitted'
pass 'local source, spaces, launcher and default/explicit workspace'
pass 'developer credentials and runtime data omitted from local release'
printf 'solution\n' > "$base/workspace/keep.txt"
mkdir -p "$HOME/.config/solvebench"
printf 'config\n' > "$HOME/.config/solvebench/keep"
old=$(readlink "$base/current")
install --prefix "$prefix" || fail 'repeat install'
[[ $(readlink "$base/current") != "$old" ]] || fail 'unique release'
[[ $(cat "$base/workspace/keep.txt") == solution && $(cat "$HOME/.config/solvebench/keep") == config ]] || fail 'user data preserved'
pass 'repeat installation preserves workspace and config'
old=$(readlink "$base/current")
if FAIL_INSTALL=1 install --prefix "$prefix"; then fail 'dependency failure accepted'; fi
[[ $(readlink "$base/current") == "$old" && ! -e "$base/.install-lock" ]] || fail 'failed installation changed current or leaked lock'
[[ -z $(find "$base/releases" -maxdepth 1 -name '.staging-*' -print -quit) ]] || fail 'staging leaked'
pass 'dependency failure preserves current and cleans staging'
if SMOKE_VERSION=0.0.0 install --prefix "$prefix"; then fail 'wrong version accepted'; fi
[[ $(readlink "$base/current") == "$old" ]] || fail 'failed smoke changed current'
pass 'version smoke failure preserves current'
mkdir -p "$tmp/unrelated/bin"
printf 'keep\n' > "$tmp/unrelated/bin/solvebench"
if install --prefix "$tmp/unrelated"; then fail 'unrelated launcher replaced'; fi
[[ $(cat "$tmp/unrelated/bin/solvebench") == keep ]] || fail 'unrelated launcher changed'
pass 'unrelated launcher preserved'
mkdir -p "$tmp/symlink/share"
ln -s "$base" "$tmp/symlink/share/solvebench"
if install --prefix "$tmp/symlink"; then fail 'symlink data root accepted'; fi
pass 'symlink data root rejected'
mkdir "$base/.install-lock"
if install --prefix "$prefix"; then fail 'concurrent install accepted'; fi
rmdir "$base/.install-lock"
pass 'existing lock rejected'
SLOW_INSTALL=1 bash "$root/install.sh" --source "$source_dir" --prefix "$prefix" > "$tmp/slow-log" 2>&1 &
installer_pid=$!
for ((attempt=0; attempt<100; attempt++)); do
  [[ ! -d "$base/.install-lock" ]] || break
  sleep 0.02
done
[[ -d "$base/.install-lock" ]] || fail 'slow installer never acquired lock'
if install --prefix "$prefix"; then fail 'parallel installer accepted'; fi
wait "$installer_pid" || fail 'first concurrent installer failed'
[[ ! -e "$base/.install-lock" ]] || fail 'successful installer leaked lock'
pass 'real concurrent install rejected while first installer succeeds'
mv "$tmp/tools/bun" "$tmp/tools/bun.off"
if install --prefix "$prefix"; then fail 'missing Bun accepted'; fi
[[ $(cat "$tmp/log") == *'Bun'* ]] || fail 'missing Bun error unclear'
mv "$tmp/tools/bun.off" "$tmp/tools/bun"
pass 'missing Bun actionable error'
if bash "$root/install.sh" --repo bad > "$tmp/log" 2>&1; then fail 'invalid repository accepted'; fi
pass 'invalid repository rejected'
mkdir -p "$source_dir/source"
printf 'release content\n' > "$source_dir/source/keep"
tar -czf "$tmp/release.tar.gz" -C "$tmp" 'source with spaces'
cat > "$tmp/tools/curl" <<'CURL'
#!/usr/bin/env bash
set -euo pipefail
[[ "$*" == *'https://github.com/example/solvebench/archive/refs/tags/v0.1.0-alpha.1.tar.gz'* ]]
cp "$MOCK_ARCHIVE" "${@: -1}"
CURL
chmod +x "$tmp/tools/curl"
MOCK_ARCHIVE="$tmp/release.tar.gz" bash "$root/install.sh" --repo example/solvebench --prefix "$tmp/remote" > "$tmp/remote-log" 2>&1 || { cat "$tmp/remote-log"; fail 'pinned remote archive installation'; }
[[ $(cat "$tmp/remote/share/solvebench/current/source/keep") == 'release content' ]] || fail 'remote archive lost source directory'
pass 'pinned remote archive retains nested source directory'


# Opt in once the app CLI exists; this installs the real frozen dependency graph.
if [[ "${1:-}" == --real-source ]]; then
  [[ -n "$real_bun" ]] || fail 'real source QA requires Bun'
  real_home="$tmp/real home"
  real_prefix="$tmp/real prefix"
  mkdir -p "$real_home"
  HOME="$real_home" PATH="$original_path" WORKBENCH_BUN="$real_bun" bash "$root/install.sh" --source "$root" --prefix "$real_prefix" > "$tmp/real-log" 2>&1 || { cat "$tmp/real-log"; fail 'real source install'; }
  for flag in --version --help; do
    HOME="$real_home" PATH="$original_path" WORKBENCH_BUN="$real_bun" "$real_prefix/bin/solvebench" "$flag" > "$tmp/real-cli" 2>&1 || { cat "$tmp/real-cli"; fail "real installed $flag"; }
  done
  [[ -z $(find "$real_prefix/share/solvebench/workspace" -mindepth 1 -print -quit) ]] || fail 'informational CLI created workspace files'
  pass 'real source frozen installation, --version and --help without terminal or DB'
fi
